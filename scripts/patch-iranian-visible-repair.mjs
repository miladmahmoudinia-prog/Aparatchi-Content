import fs from 'node:fs';

const file = process.argv[2];
if (!file) throw new Error('Runtime sync path is required.');

let source = fs.readFileSync(file, 'utf8');

const recentNeedle = '      await syncRecentIranianSeriesDiscovery();';
const recentReplacement = [
  "      if (process.env.APARATCHI_SKIP_IRANIAN_RECENT !== 'true') {",
  '        await syncRecentIranianSeriesDiscovery();',
  '      }',
].join('\n');
if (!source.includes('APARATCHI_SKIP_IRANIAN_RECENT')) {
  if (!source.includes(recentNeedle)) throw new Error('Iranian recent-discovery hook not found.');
  source = source.replace(recentNeedle, recentReplacement);
}

const archiveNeedle = 'async function syncIranianSeriesArchive() {\n';
const repairPrelude = [
  'async function syncIranianSeriesArchive() {',
  '  // Repair already-known Iranian series whose visible episode count and usable',
  '  // episode groups disagree before spending time on noisy source-page cursors.',
  '  if (!state.iranianVisibleRepairNoProgress || typeof state.iranianVisibleRepairNoProgress !== "object" || Array.isArray(state.iranianVisibleRepairNoProgress)) state.iranianVisibleRepairNoProgress = {};',
  '  if (!state.iranianVisibleRepairDeferredAt || typeof state.iranianVisibleRepairDeferredAt !== "object" || Array.isArray(state.iranianVisibleRepairDeferredAt)) state.iranianVisibleRepairDeferredAt = {};',
  '  state.iranianVisibleRepairActiveId = cleanText(state.iranianVisibleRepairActiveId || "");',
  '',
  '  const visibleRepairUsableEpisodes = (item) => (Array.isArray(item?.downloads) ? item.downloads : []).filter((group) => Number(group?.episodeNumber || 0) > 0 && episodeGroupHasUsableMedia(group)).length;',
  '  const visibleRepairExpectedEpisodes = (item, usableEpisodes) => {',
  '    const text = normalizeNumericText([item?.updateLabel, item?.episodeLabel, item?.statusLabel, item?.releaseLabel, item?.latestEpisodeLabel, item?.subtitle].filter(Boolean).join(" "));',
  '    const labelNumbers = Array.from(text.matchAll(/(?:قسمت|episode)\\s*(\\d+)/gi), (match) => nonNegativeInt(match[1], 0));',
  '    const pending = nonNegativeInt(item?.archivePendingEpisodeCount, 0);',
  '    return Math.max(',
  '      nonNegativeInt(item?.sourceEpisodeCount, 0),',
  '      nonNegativeInt(item?.episodeCount, 0),',
  '      nonNegativeInt(item?.latestEpisode?.episodeNumber, 0),',
  '      pending > 0 ? usableEpisodes + pending : 0,',
  '      ...labelNumbers,',
  '    );',
  '  };',
  '',
  '  const repairNow = Date.now();',
  '  const repairCooldownMs = 6 * 60 * 60 * 1000;',
  '  const activeRepairId = cleanText(state.iranianVisibleRepairActiveId || "");',
  '  const iranianVisibleRepairCandidates = items',
  '    .filter((item) => {',
  '      if (item?.type !== "series" || catalogVariant(item) !== "standard") return false;',
  '      const rules = classifyCatalogRules({ ...item, categoryKeys: [], categoryLabels: [] });',
  '      return rules.categoryKeys.includes("iranian-series") && !rules.isDocumentary && rules.contentKind !== "documentary";',
  '    })',
  '    .map((item) => {',
  '      const usableEpisodes = visibleRepairUsableEpisodes(item);',
  '      const expectedEpisodes = visibleRepairExpectedEpisodes(item, usableEpisodes);',
  '      const deferredAt = Date.parse(String(state.iranianVisibleRepairDeferredAt[String(item.id || "")] || "")) || 0;',
  '      return { item, usableEpisodes, expectedEpisodes, deferredAt };',
  '    })',
  '    .filter(({ item, usableEpisodes, expectedEpisodes, deferredAt }) => {',
  '      const broken = usableEpisodes === 0 || expectedEpisodes > usableEpisodes || item?.archiveComplete !== true || item?.publicationStatus !== "published";',
  '      const coolingDown = deferredAt > 0 && repairNow - deferredAt < repairCooldownMs;',
  '      return broken && !coolingDown;',
  '    })',
  '    .sort((left, right) => {',
  '      // A visible series claiming episodes while exposing zero usable episode',
  '      // groups is the worst user-facing failure. Repair those before resuming a',
  '      // partially-built active title so rows like «اهل ایران» cannot stay empty.',
  '      const zeroDiff = Number(right.usableEpisodes === 0) - Number(left.usableEpisodes === 0);',
  '      if (zeroDiff) return zeroDiff;',
  '      const leftId = String(left.item?.id || "");',
  '      const rightId = String(right.item?.id || "");',
  '      if (activeRepairId && (leftId === activeRepairId) !== (rightId === activeRepairId)) return leftId === activeRepairId ? -1 : 1;',
  '      const mismatchDiff = Number(right.expectedEpisodes > right.usableEpisodes) - Number(left.expectedEpisodes > left.usableEpisodes);',
  '      if (mismatchDiff) return mismatchDiff;',
  '      const visibleDiff = Number(Boolean(right.item?.visibilityLocked || right.item?.publicationStatus === "published")) - Number(Boolean(left.item?.visibilityLocked || left.item?.publicationStatus === "published"));',
  '      if (visibleDiff) return visibleDiff;',
  '      const expectedDiff = right.expectedEpisodes - left.expectedEpisodes;',
  '      if (expectedDiff) return expectedDiff;',
  '      const yearDiff = Number(right.item?.year || 0) - Number(left.item?.year || 0);',
  '      if (yearDiff) return yearDiff;',
  '      return String(right.item?.sourceUpdatedAt || right.item?.meaningfulUpdatedAt || "").localeCompare(String(left.item?.sourceUpdatedAt || left.item?.meaningfulUpdatedAt || ""));',
  '    });',
  '',
  '  const repairTarget = iranianVisibleRepairCandidates[0] || null;',
  '  if (repairTarget) {',
  '    const id = String(repairTarget.item.id || "");',
  '    const title = cleanText(repairTarget.item?.nameFa || repairTarget.item?.name || id);',
  '    state.iranianVisibleRepairActiveId = id;',
  '    stats.iranianSeriesCandidates += 1;',
  '    const beforeUsable = repairTarget.usableEpisodes;',
  '    const wasPublished = Boolean(repairTarget.item?.publicationStatus === "published" || repairTarget.item?.visibilityLocked);',
  '    let result;',
  '    try {',
  '      result = await processSeries({ id, type: "series" }, "iranian-visible-repair", {',
  '        requireIranian: true,',
  '        episodeStrategy: "latest",',
  '        episodeLimit: Math.min(120, Math.max(1, priorityEpisodesPerSeries)),',
  '        onlyMissing: true,',
  '      });',
  '    } catch (error) {',
  '      rememberError("iranian-visible-repair-" + id, error);',
  '      result = { added: false, reason: "request-error", retryLater: false };',
  '    }',
  '',
  '    stats.iranianSeriesProcessed += 1;',
  '    const refreshed = items.find((item) => item?.type === "series" && catalogVariant(item) === "standard" && String(item.id || "") === id) || repairTarget.item;',
  '    const afterUsable = visibleRepairUsableEpisodes(refreshed);',
  '    const expectedAfter = visibleRepairExpectedEpisodes(refreshed, afterUsable);',
  '    const newlyPublished = Boolean(!wasPublished && refreshed?.publicationStatus === "published" && refreshed?.archiveComplete === true);',
  '    const completed = Boolean(refreshed?.archiveComplete === true && refreshed?.publicationStatus === "published" && afterUsable > 0);',
  '    const progressed = Boolean(afterUsable > beforeUsable || Number(result?.addedEpisodes || 0) > 0 || result?.added);',
  '    if (progressed) stats.iranianSeriesAddedOrUpdated += 1;',
  '',
  '    let deferred = false;',
  '    if (completed) {',
  '      delete state.iranianVisibleRepairNoProgress[id];',
  '      delete state.iranianVisibleRepairDeferredAt[id];',
  '      state.iranianVisibleRepairActiveId = "";',
  '    } else if (progressed || result?.retryLater) {',
  '      state.iranianVisibleRepairNoProgress[id] = 0;',
  '      delete state.iranianVisibleRepairDeferredAt[id];',
  '    } else {',
  '      const attempts = nonNegativeInt(state.iranianVisibleRepairNoProgress[id], 0) + 1;',
  '      state.iranianVisibleRepairNoProgress[id] = attempts;',
  '      if (attempts >= 3) {',
  '        state.iranianVisibleRepairDeferredAt[id] = new Date().toISOString();',
  '        state.iranianVisibleRepairActiveId = "";',
  '        deferred = true;',
  '      }',
  '    }',
  '',
  '    rememberDiagnostic("iranianSeriesDiagnostics", {',
  '      id,',
  '      title,',
  '      result: completed ? "completed" : progressed ? "advanced" : "rejected",',
  '      reason: result?.reason || "",',
  '      addedEpisodes: Math.max(Number(result?.addedEpisodes || 0), afterUsable - beforeUsable),',
  '      remainingEpisodeCount: Number(result?.remainingEpisodeCount || Math.max(0, expectedAfter - afterUsable)),',
  '      retryLater: Boolean(result?.retryLater),',
  '      newlyPublished,',
  '      meaningfulProgress: progressed,',
  '      discovery: "visible-repair",',
  '      expectedEpisodes: expectedAfter,',
  '      usableEpisodes: afterUsable,',
  '      repairDeferred: deferred,',
  '    });',
  '',
  '    await persistSyncCheckpoint("iranian-visible-repair-" + id);',
  '    return;',
  '  }',
  '',
].join('\n');

if (!source.includes('const iranianVisibleRepairCandidates')) {
  if (!source.includes(archiveNeedle)) throw new Error('Iranian archive hook not found.');
  source = source.replace(archiveNeedle, repairPrelude);
}

fs.writeFileSync(file, source);
